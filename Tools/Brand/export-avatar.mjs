// Export the existing MoMo geometry in a deterministic, front-facing open-eyed pose.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const generated = fs.readFileSync('Vendor/BibleStrongAvatar/upstream/src/features/export/standaloneEngine.generated.ts', 'utf8');
const prefix = '// Generated by scripts/generate-standalone-engine.mjs. Do not edit.\nexport const standaloneEngineSource = ';
assert(generated.startsWith(prefix));
let source = JSON.parse(generated.slice(prefix.length).trim());
// Static 1024px artwork needs a denser silhouette than the small animated avatar.
for (const [before, after] of [
  ['we=33,Te=73', 'we=129,Te=257'],
  ['length:17},(e,n)=>{let r=-Math.PI/2+n/16*Math.PI;return Array.from({length:49},(e,n)=>{let i=-Math.PI+n/48*Math.PI*2',
   'length:65},(e,n)=>{let r=-Math.PI/2+n/64*Math.PI;return Array.from({length:193},(e,n)=>{let i=-Math.PI+n/192*Math.PI*2'],
]) {
  assert.equal(source.split(before).length, 2, 'Pinned silhouette sampler changed');
  source = source.replace(before, after);
}
const context = vm.createContext({});
vm.runInContext(source, context);
const engine = context.AvatarProceduralEngine;
const data = JSON.parse(fs.readFileSync('Vendor/BibleStrongAvatar/momoagent-avatar.json', 'utf8'));
const expression = {
  ...data.expressions.listening,
  headX: 0, headY: 0, headZ: 0,
  widthLeft: 17, widthRight: 17, heightLeft: 29, heightRight: 29,
  positionXLeft: 0, positionXRight: 0, positionYLeft: 12, positionYRight: 12,
  leftAngle: 0, rightAngle: 0, eyeMotion: 'none', bodyMotion: 'none',
};
const geometry = engine.renderAvatar(engine.poseFromExpression(expression), data.avatar.surface, 1, {
  includeWire: false, bodyNodes: data.avatar.bodyNodes, eyeOffset: { x: 0, y: 0 },
});
assert(geometry.leftVisible && geometry.rightVisible);
for (const path of [geometry.headPath, geometry.leftPath, geometry.rightPath]) {
  assert(path.length > 0 && !/NaN|Infinity/.test(path));
}
const silhouette = [
  ...geometry.backPaths.map(d => `<path d="${d}"/>`),
  `<path fill-rule="evenodd" d="${geometry.headPath} ${geometry.leftPath} ${geometry.rightPath}"/>`,
  ...geometry.frontPaths.map(d => `<path d="${d}"/>`),
].join('');
const svg = (background, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="-150 -168 300 300">${background}<g fill="${body}">${silhouette}</g></svg>\n`;
fs.writeFileSync('docs/design/brand/avatar-front.svg', svg('<rect x="-150" y="-168" width="300" height="300" fill="#171717"/>', '#f4f4f4'));
fs.writeFileSync('docs/design/brand/avatar-front-template.svg', svg('', '#000000'));
console.log('Exported MoMo front pose: zero head rotation, both eyes fully open.');
