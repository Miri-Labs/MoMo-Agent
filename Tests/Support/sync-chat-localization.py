"""Generate the small WebKit dictionary from the shared native string catalog."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "Packages/MoMoAgentKit/Sources/MoMoContracts/Resources/Localizable.xcstrings"
OUTPUT = ROOT / "Apps/iPhoneApp/Features/Assistant/Rendering/Web/chat-localization.js"
TEMPLATE = '''/* Generated by Tests/Support/sync-chat-localization.py. */
(() => {
  'use strict';
  const translations = TABLE;
  let locale = 'zh-Hans';
  globalThis.MoMoChatLocalization = {
    get locale() { return locale; },
    setLocale(value) {
      const language = String(value || 'en').toLowerCase().split(/[-_]/)[0];
      locale = language === 'zh' ? 'zh-Hans' : ['en','ja','ko'].includes(language) ? language : 'en';
    },
    text(key, ...arguments_) {
      const text = translations[locale]?.[key] ?? (locale === 'zh-Hans' ? key : translations.en[key]) ?? key;
      return text.replace(/\\{(\\d+)\\}/g, (_, index) => String(arguments_[Number(index)] ?? ''));
    }
  };
})();
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="Update the generated WebKit dictionary; otherwise check it.")
    arguments = parser.parse_args()
    entries = json.loads(CATALOG.read_text())["strings"]
    selected = {key: entry for key, entry in entries.items()
                if entry.get("comment", "").startswith("Chat renderer UI")}
    assert selected, "Mark WebKit keys with a 'Chat renderer UI' translator comment."
    translations = {language: {key: entry["localizations"][language]["stringUnit"]["value"]
                               for key, entry in sorted(selected.items())}
                    for language in ["en", "ja", "ko"]}
    expected = TEMPLATE.replace("TABLE", json.dumps(translations, ensure_ascii=False, indent=2))
    if arguments.write:
        OUTPUT.write_text(expected)
    else:
        assert OUTPUT.read_text() == expected, "Run uv run Tests/Support/sync-chat-localization.py --write"
    print(f"PASS {len(selected)} shared WebKit localization keys")


if __name__ == "__main__":
    main()
